///       正在处理：01 和室でこっそりエチュード手コキ.flac  （第 1/3 个，还剩 2 个）
///     未开始时显示"队列共 N 个文件（未开始）"。
///     文件名超过 42 字符时中间省略，保留头尾（前面是系列名、
///     后面是集数/标题，中间往往是一长串不带信息量的路径片段）。
///
/// 1.7.2 相对 1.7.1 的变化：
///   · 【修 bug】第1步只认 mp4/mkv，用户把 FLAC/WAV 音频拖进来时
///     会被当成"不是视频"跳过，扫描 0pre 得到 0 个、退出码 1、整批中止。
///     但纯音频（ASMR 音声）本来就是这工具的主要用途之一。
///     现在支持 11 种视频格式 + 8 种音频格式。
///
/// 1.7.1 相对 1.7 的变化：
///   · 修正界面起始提示里的步骤顺序（还是旧的"分离→VAD"）。
///   · 修正 ETA 权重表 —— 顺序变了，而且分离只处理语音段之后
///     它的相对占比从 0.62 降到约 0.55 并后移一位。
///
/// 1.7 相对 1.6.1 的变化：
///   · 【架构改动】VAD 提前到人声分离之前。
///     原来：提取 → 分离 → VAD → 识别
///     现在：提取 → VAD → 分离 → 识别
///     理由：VAD 不需要人声（在原始音频上检测语音活动即可），
///     而分离耗时与音频长度严格成正比。
///     实测（L 盘真实音声 + H 盘真实视频）：
///       12 分钟视频：分离 65s → 9.45s（语音只占 15%）
///       30 分钟音声：分离 122s → 51.84s（语音占 41.8%）
///       整条链路 145s → 58.7s（省 60%），字幕质量不变、字幕零漏检。
///   · b_分离人声.py 重写：按 VAD 段拼接 → 只分离语音 → 填回原长度。
///     填回后时间轴天然正确，识别环节不用做任何映射。
///   · c_人声检测.py：输入从 1audio 改为 0pre，并额外导出 .vad.json。
///   · d_语音识别.py：vad_filter=True，静音不参与识别（识别 80s → 7.15s）。
///
/// 1.6.1 相对 1.6 的变化：
///   · 【修 bug】断点续跑。队列索引不可靠 —— DSH 更新重启会把翻译器
///     一起杀掉，索引来不及存盘，于是重开之后从头又跑一遍，把 15 个
///     早就有字幕的文件重新处理了（每个 15~30 分钟）。
///     现在开跑前先按【产物】剔除：视频旁有 <名字>.chs.srt、
///     或 3asr\<名字>.srt 存在 → 这个文件直接跳过。
///     产物是事实，索引只是记录；记录会丢，事实不会。
///     同时每完成一个文件就存一次队列，减少信息损失。
///
/// 1.6 相对 1.5 的变化：
///   · 【新功能】记忆上次的队列。文件列表和处理进度存到
///     \\_file_queue.txt（第1行是索引，之后每行一个路径）。
///     程序启动时如果发现有队列，会弹窗问「恢复 / 清空」：
///       恢复 → 填回列表，从上次的位置继续（跳过已完成的）
///       清空 → 删掉文件，从空列表开始
///     已删除的源文件会自动过滤掉。写盘用裸文本不用 JSON ——
///     不想为这一个功能引 serde，而且路径里的中文和反斜杠在 JSON 里
///     转义更麻烦。
///
/// 1.5 相对 1.4 的变化：
///   · 【架构改动】从"按步骤批量"改成"逐个文件走完四步再清理"。
///     以前 25 个文件一起走第1步、再一起走第2步，中间产物同时堆在磁盘上
///     （每步 flac 700MB + wav 1.5GB × 25 ≈ 55 GB 起步），实测把 200 GB
///     的 D 盘塞满，导致 13 次 No space left on device、部分 wav 写成半截。
///     现在每轮只处理一个文件、做完立刻清中间产物：
///       磁盘峰值 70 GB → 2.7 GB
///       代价：每个文件重新加载三个模型，约多花 45 秒/文件
///   · 界面日志会标明"文件 3/25: xxx.mp4"，进度一目了然。
///
/// 1.4 相对 1.3 的变化：
///   · 修掉「长视频人声分离失败」—— audio-separator 的无重叠固定切块
///     会产生超短的"尾巴块"，太短时它判定 empty、放弃【整个文件】。
///     去掉 chunk_duration 后整段处理，实测 2 小时视频 9 分 51 秒跑完。
///   · 第2步开跑前检查磁盘空间（按文件数动态估算），
///     不够就拒绝启动 —— 避免跑一整夜才发现磁盘满。
///   · 第2步产出检查升级成【校验 WAV 完整性】（RIFF/WAVE 头 + 尺寸吻合），
///     不再只是数文件个数。磁盘满产生的半截文件会被识别出来并挪到
///     ！audio\_corrupted\。
///   · 第3步单文件失败不再中止整批，跳过并继续，最后汇总。
