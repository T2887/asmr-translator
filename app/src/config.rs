/// 支持的音视频扩展名（和 Python 版的 VIDEO_AUDIO_EXTS 保持一致）
pub const VIDEO_AUDIO_EXTS: [&str; 5] = [".mp4", ".mkv", ".flac", ".wav", ".mp3"];

/// 判断一个路径是不是我们支持的音视频
pub fn is_video_audio(path: &str) -> bool {
    let lower = path.to_lowercase();
    VIDEO_AUDIO_EXTS.iter().any(|e| lower.ends_with(e))
}

/// 把一个拖进来的路径展开成"可以直接进列表的文件路径"。
///
///   · 是文件 → 原样返回（【不】按扩展名过滤 —— 用户明确拖进来的东西
///     就该被接受，哪怕扩展名不在白名单里，这样他才能看到"我拖了但没进列表"
///     之外的实际结果）
///   · 是目录 → 递归找出里面所有音视频文件
///   · 其他（快捷方式之类）→ 跳过
///
/// 递归用显式的栈而不是函数自身递归，免得目录很深时爆栈。
pub fn expand_dropped_path(path: &str) -> Vec<String> {
    let p = std::path::Path::new(path);
    if p.is_file() {
        return vec![path.to_string()];
    }
    if !p.is_dir() {
        return Vec::new();
    }

    let mut out = Vec::new();
    let mut stack = vec![p.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(rd) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in rd.flatten() {
            let ep = entry.path();
            if ep.is_dir() {
                stack.push(ep);
            } else if is_video_audio(&ep.to_string_lossy()) {
                out.push(ep.to_string_lossy().to_string());
            }
        }
    }
    // 排序。用栈遍历出来的顺序是不确定的（跟目录项在磁盘上的排列有关），
    // 同一个文件夹扫两次可能给出不同的列表 —— 那样用户会以为文件变了。
    // Python 版这里也是 sorted()。
    out.sort();
    out
}

