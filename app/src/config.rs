///       · Tick 里只有 Some(prev) 才限速；None 时直接用 raw
///
///     效果：切换后的第一帧直接显示真实值（用户看到数字跳一下，
///     但那是物理事实），从第 2 帧起重新启用限速消除抖动。
///     不再有"卡在旧值上慢慢爬"的问题。
///
///   · 删掉 1.16.2 的 stage_fresh 时间特例。
///
/// 1.16.2 相对 1.16.1 的变化：
///   · 【修 bug】第4步刚开始时「预估剩余」卡住不动（用户看到「约 6 分 18 秒」
///     停了一二十秒才重新开始变）。
///
///     根因：1.16.1 把限速改成绝对增量「每秒最多涨 8 秒」之后，
///     阶段切换时的巨大落差追不上 ——
///       第3步结束时显示「2 分 10 秒」
///       第4步真实剩余可能是「8 分 23 秒」
///       用每秒 8 秒的速度要追 46 秒，用户看到的就是卡住。
///
///     修法：阶段切换后的前 10 秒不做限速，直接显示真实值。
///     这 10 秒用户还没形成预期，给了也会接受；
///     之后再启用限速，避免抖动。
///
///   · 用户实测确认：1.16.1 的抖动修复有效
///     「之后时间就开始动了，没有之前剧烈的抖动，是稳步下降的」。
///
/// 1.16.1 相对 1.16 的变化：
///   · 【改进】按千问大小姐的 review 调整 ETA 平滑策略。
///
///     她指出我 1.16 的归因不完整：
///       「限速器算错不是主因，是放大器。即使限速器完全失效，
///         ETA 也不会从 84 跳到 233 —— 跳动的根源是 rate 的真实突变。
///         Whisper 卡了 12 秒没进展，done 停滞而 elapsed 增长，
///         rate 必然下降，ETA 必然上升。
///         限速器算错只是让波动被放大。」
///
///     三处调整：
///       ① EMA 系数 0.85/0.15 → 0.95/0.05
///          按时间常数推导：tau ≈ 1/alpha 个 tick，Tick 100ms，
///          alpha=0.05 → tau ≈ 2 秒。原来的 0.15 只有 0.66 秒，
///          比观测到的 12 秒卡顿短得多，所以跟着卡顿一起跳。
///
///       ② 限速从【百分比】改成【绝对增量】
///          百分比的毛病：ETA 越大，一次允许的跳变越大
///          （233 × 1.12 = 一次能涨 28 秒，越到后面越跳）。
///          改成每秒最多涨 8 秒、降 25 秒（每 tick 涨 0.8 / 降 2.5）。
