/// d_语音识别.py 实际打印的字幕行格式：  [475.93s -> 479.49s]: 文本
///
/// ⚠️ 数字后面那个 `s` 一定要写成 `s?`（可选）。Python 版早期就是漏了它，
///    导致一行都匹配不上、预览区永远空白 —— 而且不报错，只是"什么都没收到"。
///    这种静默失效最难查，所以这里写死注释提醒。
/// 匹配 tqdm 进度条里的 "已完成/总数"。
///
/// separator（人声分离）和 faster-whisper（语音识别）都会输出形如
///     12%|█▏        | 87/706 [01:23<09:53,  1.04it/s]
/// 的一行。其中 `87/706` 是当前文件的处理进度 —— 这是整个流水线里
/// 唯一【细粒度、实时、且不依赖文件个数】的进度来源。
///
/// 为什么不能用"数输出目录的文件数"代替：长视频场景通常只有一个文件，
/// 那样算出来的比例要么 0 要么 1，全程都是 0，ETA 会严重失真
/// （实测：2 小时视频跑了 2 分钟时，界面显示"预计剩余 1 小时 12 分"，
///   而实际总耗时只有 12 分钟）。
///
/// `\d+/\d+` 外面用非贪婪限定了前后文，避免误匹配字幕行里的时间戳
/// （字幕行是 "[596.17s -> 598.34s]: 文本"，没有 `|` 和 `it/s]` 特征）。
/// 匹配第2步 VAD 脚本打印的语音时长。
///
/// ★ 这一行来自 c_人声检测.py：
///       VAD段已导出: DVMM-322.vad.json（2054 段 / 3699.8 秒）
///
/// 之前匹配的是 `VAD: N 段 / X.Xs（占 Y%）` —— 那行其实是
/// 【第3步 b_分离人声.py】读了 vad.json 之后打印的统计。
/// 而解析代码写的是 `if stage == 2`，于是永远错过：
///   → cur_speech 恒为 0
///   → sep_est / asr_est 全为 0
///   → ETA 退化成常量 TAIL = 10 秒，界面上"约 10 秒"一直不变
/// 实测踩过这个坑（2026-10-18 DVMM-322）。
///
/// 注意括号是全角的，单位是「秒」。
pub fn vad_speech_re() -> &'static regex::Regex {
    static RE: OnceLock<regex::Regex> = OnceLock::new();
    RE.get_or_init(|| {
        regex::Regex::new(r"VAD段已导出.*?段\s*/\s*([\d.]+)\s*秒").unwrap()
    })
}

pub fn tqdm_re() -> &'static regex::Regex {
    static RE: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
    RE.get_or_init(|| {
        // ★ 必须支持小数。
        //
        //   第3步 audio-separator 的进度是整数块号：  8/173
        //   第4步 faster-whisper 的进度是【音频秒数】：30.0/1376.54
        //
        //   原来写 (\d+)/(\d+)，第二段遇到小数点就断，一行都匹配不上，
        //   于是第4步的 stage_frac 恒为 0 —— 进度条从 50% 直接跳到 100%，
        //   整段 3 分多钟的识别过程中进度条纹丝不动。
        //   实测症状：用户反馈"50 突变到 100"。
        regex::Regex::new(r"\|\s*([\d.]+)/([\d.]+)\s*\[").expect("tqdm 正则写错了")
    })
}

/// 匹配 tqdm 里的「已用时间<剩余时间」：
///     [00:01<01:12, 18.53seconds/s]     → 已用 1 秒，剩余 72 秒
///     [02:54<00:00, 21.17seconds/s]     → 已用 174 秒，剩余 0
///     [1:02:15<00:38, 2.1it/s]          → 支持带小时的格式
///
/// ★ 为什么要用它：tqdm 自己就算好了剩余时间，而且是按【真实处理速度】
///   实时更新的 —— 比我们任何成本模型都准。实测第4步识别的 tqdm 是
///   按音频秒数推进的，它给的 ETA 误差在 5% 以内。
pub fn tqdm_eta_re() -> &'static regex::Regex {
    static RE: OnceLock<regex::Regex> = OnceLock::new();
    RE.get_or_init(|| {
        regex::Regex::new(r"\[(\d+:\d+(?::\d+)?)<(\d+:\d+(?::\d+)?)").unwrap()
    })
}

/// 把 tqdm 的 MM:SS 或 HH:MM:SS 解析成秒。
pub fn parse_hms(s: &str) -> Option<f64> {
    let parts: Vec<&str> = s.split(':').collect();
    match parts.len() {
        2 => Some(parts[0].parse::<f64>().ok()? * 60.0 + parts[1].parse::<f64>().ok()?),
        3 => Some(
            parts[0].parse::<f64>().ok()? * 3600.0
                + parts[1].parse::<f64>().ok()? * 60.0
                + parts[2].parse::<f64>().ok()?,
        ),
        _ => None,
    }
}

/// 匹配第3步分离脚本打印的音频总长：
///     填回原长度: 6392.5s → xxx.wav
pub fn audio_total_re() -> &'static regex::Regex {
    static RE: OnceLock<regex::Regex> = OnceLock::new();
    RE.get_or_init(|| regex::Regex::new(r"填回原长度:\s*([\d.]+)s").unwrap())
}

pub fn translation_re() -> &'static regex::Regex {
    use std::sync::OnceLock;
    static RE: OnceLock<regex::Regex> = OnceLock::new();
    RE.get_or_init(|| {
        regex::Regex::new(r"^\[\s*([\d.]+)s?\s*->\s*([\d.]+)s?\s*\]\s*:\s*(.+)$")
            .expect("字幕行的正则是写死的常量，不可能编译失败")
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    // 这个测试的存在理由：Python 版早期漏了 `s?`，导致一行都匹配不上、
    // 预览区永远空白，而且【不报错】。所以这里把所有真实出现过的形状都钉住。
    #[test]
    fn 字幕行各种形状都能解析() {
        let re = translation_re();

        // 真实格式（带 s）—— 这是 d_语音识别.py 实际打印的样子
        let c = re.captures("[475.93s -> 479.49s]: 就算是机器也是要先烘焙再磨炼的吧？").unwrap();
        assert_eq!(&c[1], "475.93");
        assert_eq!(&c[2], "479.49");
        assert_eq!(&c[3], "就算是机器也是要先烘焙再磨炼的吧？");

        // 不带 s 的老格式也要能匹配（s? 就是为这个加的）
        let c = re.captures("[12.93 -> 17.87]: 文本").unwrap();
        assert_eq!(&c[1], "12.93");

        // 中括号内外有多余空格
        let c = re.captures("[ 8.5s -> 9.0s ] : 空格测试").unwrap();
        assert_eq!(&c[3], "空格测试");

        // 纯数字文本
        let c = re.captures("[100s -> 200s]: 1071").unwrap();
        assert_eq!(&c[3], "1071");
    }

    #[test]
    fn 非字幕行必须原样拒绝() {
        let re = translation_re();
        // 这几条都是脚本会打印的真实日志行，绝不能被当成字幕
        for bad in [
            "Collecting ffmpeg 8.0@full-shared",
            "Requirement already satisfied: ffmpeg==8.0.1",
            "第3步 人声检测 —— 识别到 1071 个语音片段",
            "错误：目录不存在或为空",
            "[警告] 这一行是 stderr",
            "",
        ] {
            assert!(
                re.captures(bad).is_none(),
                "这行不该被当成字幕: {bad:?}"
            );
        }
    }
}

#[cfg(test)]
mod expand_tests {
    use super::*;

    fn scene() -> std::path::PathBuf {
        // ★ 目录名必须【每个测试唯一】。
        //
        //   原来写死成 "asmr_expand_test"，而这个 crate 里不止一个测试
        //   会建同一套目录；cargo test 默认多线程跑，两个测试同时
        //   remove_dir_all + create_dir_all 同一个路径就会互相踩 ——
        //   表现是随机某个测试报 "文件不存在"，重跑又好了。
        //   实测遇到过：一次 FAILED 10 passed; 1 failed，紧接着重跑 11/11。
        //
        //   用线程名拼一个唯一后缀就彻底避免（比时间戳更稳，
        //   因为同一秒内也可能有多个测试并行启动）。
        let tid = format!("{:?}", std::thread::current().id())
            .replace(|c: char| !c.is_alphanumeric(), "");
        let root = std::env::temp_dir().join(format!("asmr_expand_test_{tid}"));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("子目录").join("更深一层")).unwrap();
        std::fs::write(root.join("a.mp4"), "").unwrap();
        std::fs::write(root.join("b.flac"), "").unwrap();
        std::fs::write(root.join("忽略我.txt"), "").unwrap();
        std::fs::write(root.join("子目录").join("c.mkv"), "").unwrap();
        std::fs::write(root.join("子目录").join("更深一层").join("d.wav"), "").unwrap();
        root
    }

    // 拖文件夹进来要递归展开，而且只收音视频 ——
    // 用户的下载目录里往往混着 srt、jpg、nfo，不该一股脑进列表。
    #[test]
    fn expand_dir_recursively_and_filter() {
        let root = scene();
        let found = expand_dropped_path(&root.to_string_lossy());

        let names: Vec<String> = found
            .iter()
            .map(|p| std::path::Path::new(p).file_name().unwrap().to_string_lossy().to_string())
            .collect();

        for want in ["a.mp4", "b.flac", "c.mkv", "d.wav"] {
            assert!(names.contains(&want.to_string()), "应该找到 {want}，实际 {names:?}");
        }
        assert!(!names.contains(&"忽略我.txt".to_string()), "不该收非音视频文件");
        assert_eq!(found.len(), 4, "应该正好 4 个，实际 {names:?}");

        let _ = std::fs::remove_dir_all(&root);
    }

    // 直接拖单个文件进来时【不按扩展名过滤】——
    // 用户明确拖的东西就该被接受，让他看到真实结果，
    // 而不是莫名其妙什么都没发生。
    #[test]
    fn expand_single_file_keeps_any_extension() {
        let root = scene();
        let odd = root.join("忽略我.txt");
        let found = expand_dropped_path(&odd.to_string_lossy());
        assert_eq!(found.len(), 1, "单文件应该原样返回");
        assert!(found[0].ends_with("忽略我.txt"));

        let _ = std::fs::remove_dir_all(&root);
    }

    // 不存在的路径、空目录 → 返回空，不能 panic
    #[test]
    fn expand_missing_or_empty_is_empty() {
        assert!(expand_dropped_path(r"Z:
ope
othing").is_empty());

        let d = std::env::temp_dir().join("asmr_expand_empty");
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        assert!(expand_dropped_path(&d.to_string_lossy()).is_empty());
        let _ = std::fs::remove_dir_all(&d);
    }
}
