// config.rs —— 集中管理路径和常量
//
// 路径【不写死】。打包之后程序可能被装到任何地方（甚至别的盘），
// 写死 D:\ASMRASR 会导致别人一装上就找不到脚本和 Python 环境。
//
// 查找顺序：
//   1. 环境变量 ASMR_WORK_DIR —— 调试时用来指向别的目录
//   2. exe 所在目录            —— 打包后的正常运行方式
//   3. 开发时的兜底            —— exe 在 target\debug\ 下，往上找项目根
//   4. 最后兜底 D:\ASMRASR

use std::path::PathBuf;
use std::sync::OnceLock;

/// 四个 Python 脚本所在的子目录（相对工作目录）。
///
/// 放在子目录里是为了让发布目录的根干净 —— 用户打开文件夹只看到
/// exe、启动器、说明，不用面对一堆 .py。
///
/// 为什么不影响脚本里的 `from settings import config`：
///   Python 会自动把【脚本所在目录】加进 sys.path，所以 settings.py
///   跟脚本一起放进 app\ 之后照样能导入。
///
/// 为什么不影响脚本里的相对路径（"0pre" 之类）：
///   那些路径是相对【工作目录】的，而工作目录由 run_script 的
///   current_dir 设成发布根目录 —— 不是脚本所在目录。
pub const SCRIPTS_SUBDIR: &str = "app";

/// 定位工作目录。只算一次（结果缓存），之后所有调用都拿同一份。
fn resolve_work_dir() -> &'static str {
    static DIR: OnceLock<String> = OnceLock::new();
    DIR.get_or_init(|| {
        // 1. 环境变量优先
        if let Ok(v) = std::env::var("ASMR_WORK_DIR") {
            let v = v.trim().to_string();
            if !v.is_empty() {
                return v;
            }
        }

        // 2. exe 所在目录。
        //    判断依据：这个目录下有没有 app\a_提取音频.py。
        //    （脚本现在装在 app\ 子目录里，不再散在根目录。）
        //    开发时 exe 在 <项目>\target\debug\ 下，那时这个目录里没有
        //    app\，所以第 3 步会把它纠正到项目根。
        if let Ok(exe) = std::env::current_exe() {
            if let Some(dir) = exe.parent() {
                if dir.join(SCRIPTS_SUBDIR).join("a_提取音频.py").is_file() {
                    return dir.to_string_lossy().to_string();
                }
                // 3. 往上看几层，找放着脚本的那一层
                let mut cur: Option<PathBuf> = Some(dir.to_path_buf());
                for _ in 0..4 {
                    let Some(d) = cur else { break };
                    if d.join(SCRIPTS_SUBDIR).join("a_提取音频.py").is_file() {
                        return d.to_string_lossy().to_string();
                    }
                    cur = d.parent().map(|p| p.to_path_buf());
                }
                // 退一步：开发时 exe 在 target\debug 下，往上找 4 层应该
                // 能到项目根；找不到说明目录结构异常，交给下面的兜底。
            }
        }

        // 4. 最后兜底：exe 所在目录（哪怕里面还没有 app\，至少不会
        //    指向一个别人机器上不存在的绝对路径）。
        //
        //    ★ 这里曾经是 `r"D:\ASMRASR"` —— 硬编码的开发机绝对路径。
        //      开源之后别人在这台机器上跑，那个目录不存在，程序会
        //      静默用一个无效路径去拼脚本位置，报出来的错误和真实原因
        //      完全无关（"找不到脚本"而不是"工作目录解析失败"）。
        if let Ok(exe) = std::env::current_exe() {
            if let Some(dir) = exe.parent() {
                return dir.to_string_lossy().to_string();
            }
        }
        ".".to_string()
    })
}

/// 工作目录：四个脚本住在这儿，也在这儿运行（脚本里用的是相对路径）
pub fn work_dir() -> &'static str {
    resolve_work_dir()
}

/// Python 解释器：优先用工作目录下的 env\python.exe，找不到再退回 PATH。
pub fn python_exe() -> String {
    // ① 首选：程序自己目录下的内置环境
    let local = PathBuf::from(work_dir()).join(r"env\python.exe");
    if local.is_file() {
        return local.to_string_lossy().to_string();
    }

    // ② 环境变量覆盖 —— 调试或者多环境并存时用，避免往源码里写死路径。
    //
    //    ★ 这里曾经是一串硬编码的绝对路径（`D:\ASMRASR\env\python.exe` 之类），
    //      目录一改名或换机器就全指向死路径，run_script 启动子进程直接失败。
    //      实测症状：cargo test 里 kill_current_really_kills_the_child 报
    //      "子进程没能启动，测试前提不成立"，卡 15 秒才失败。
    //
    //      开源之后这种写死更不可接受：别人机器上根本没有那些目录。
    //      所以改成读环境变量，源码里不出现任何本机路径。
    if let Ok(v) = std::env::var("ASMR_PYTHON") {
        let v = v.trim().to_string();
        if !v.is_empty() && PathBuf::from(&v).is_file() {
            return v;
        }
    }

    // ③ 最后退回裸名字，让系统按 PATH 去找。
    //    找不到时 run_script 返回 Err，调用方报错 —— 至少错误信息清楚，
    //    比指向一个不存在的绝对路径要好。
    "python".to_string()
}

